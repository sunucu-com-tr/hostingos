//! Built-in document labels (tr / en). The texts follow the web invoice's
//! `client.invoices.*` catalog keys so the PDF and the HTML read the same; they
//! live here because PDFs are also rendered by the background worker (e-mail
//! attachments), which has no access to the web layer's catalog.

use hos_core::domain::Locale;

/// Labels of an invoice-like document.
